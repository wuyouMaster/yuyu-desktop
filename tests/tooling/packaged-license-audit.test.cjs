const { test } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, mkdirSync, writeFileSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { createRequire } = require('node:module')
const builderRequire = createRequire(require.resolve('electron-builder'))
const asar = createRequire(builderRequire.resolve('app-builder-lib'))('@electron/asar')
const { auditPackageLicenseFiles, normalizeArchivePath } = require('../../scripts/audit-packaged-license-files.cjs')

test('normalizes ASAR listing paths on macOS and Windows', () => {
  assert.equal(normalizeArchivePath('/node_modules/fixture/package.json'), 'node_modules/fixture/package.json')
  assert.equal(normalizeArchivePath('\\node_modules\\fixture\\package.json'), 'node_modules/fixture/package.json')
})

test('inventories nested packages without treating another package license as their own', async (t) => {
  const root = mkdtempSync(join(tmpdir(), 'synthetic-license-audit-'))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const outer = join(root, 'input/node_modules/fixture-parent')
  const inner = join(outer, 'node_modules/@fixture/child')
  mkdirSync(inner, { recursive: true })
  writeFileSync(join(outer, 'package.json'), JSON.stringify({ name: 'fixture-parent', version: '1.0.0', license: 'MIT' }))
  writeFileSync(join(outer, 'LICENSE'), 'Synthetic fixture license')
  writeFileSync(join(inner, 'package.json'), JSON.stringify({ name: '@fixture/child', version: '2.0.0', license: 'MIT' }))
  const archive = join(root, 'app.asar')
  await asar.createPackage(join(root, 'input'), archive)
  const result = auditPackageLicenseFiles(archive)
  assert.equal(result.packageCount, 2)
  assert.equal(result.unresolved.length, 1)
  assert.equal(result.unresolved[0].name, '@fixture/child')
  assert.equal(result.unresolved[0].declaredLicense, 'MIT')
  assert.deepEqual(result.unresolved[0].licenseFiles, [])
})

test('reports unreadable metadata even if a license filename exists', async (t) => {
  const root = mkdtempSync(join(tmpdir(), 'synthetic-license-audit-'))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const pkg = join(root, 'input/node_modules/fixture-invalid')
  mkdirSync(pkg, { recursive: true })
  writeFileSync(join(pkg, 'package.json'), '{')
  writeFileSync(join(pkg, 'LICENSE'), 'Synthetic fixture license')
  const archive = join(root, 'app.asar')
  await asar.createPackage(join(root, 'input'), archive)
  const result = auditPackageLicenseFiles(archive)
  assert.equal(result.packageCount, 1)
  assert.equal(result.unresolved[0].error, 'unreadable package metadata')
})

test('does not count an empty license file as evidence', async (t) => {
  const root = mkdtempSync(join(tmpdir(), 'synthetic-license-audit-'))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  const pkg = join(root, 'input/node_modules/fixture-empty')
  mkdirSync(pkg, { recursive: true })
  writeFileSync(join(pkg, 'package.json'), JSON.stringify({ name: 'fixture-empty', version: '1.0.0' }))
  writeFileSync(join(pkg, 'LICENSE'), '')
  const archive = join(root, 'app.asar')
  await asar.createPackage(join(root, 'input'), archive)
  assert.equal(auditPackageLicenseFiles(archive).unresolved[0].name, 'fixture-empty')
})
